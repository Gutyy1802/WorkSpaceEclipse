package ceu.dam.psp.wallapop.exceptions;

public class ApiConexionException extends Exception {

	/**
	 * 
	 */
	private static final long serialVersionUID = 3241895207549537636L;

	public ApiConexionException() {
	}

	public ApiConexionException(String arg0) {
		super(arg0);
	}

	public ApiConexionException(Throwable arg0) {
		super(arg0);
	}

	public ApiConexionException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public ApiConexionException(String arg0, Throwable arg1, boolean arg2, boolean arg3) {
		super(arg0, arg1, arg2, arg3);
	}

}
